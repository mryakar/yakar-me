const lookup = (table: Record<string, string>, what: string, verbatim?: RegExp) => (value: string) => {
  if (verbatim?.test(value)) return value;
  const hit = table[value];
  if (hit === undefined) throw new Error(`No Turkish ${what} for "${value}" — add it to src/i18n/ui.ts`);
  return hit;
};

